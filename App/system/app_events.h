#pragma once

#include <stdint.h>
#include "FreeRTOS.h"
#include "queue.h"

/*
 * AppEvents — единая шина событий/команд (EventBus)
 *
 * Принцип:
 * - DoorTask публикует события о физике/режимах двери (OPEN/CLOSE/ALARM/timeout/сигнализация)
 * - LogicCore/CommsTask потребляет эти события, логирует, применяет системную логику,
 *   а также публикует команды (EVT_CMD_*) для door-model API.
 */

typedef enum
{
    EVT_NONE = 0,

    /* ------------------------------------------------------------
     * Door -> System (локальные события двери)
     * ------------------------------------------------------------ */
    EVT_DOOR_OPEN,
    EVT_DOOR_CLOSE,

    /* Кнопка Alarm (локальный источник).
     * Исторически это событие сообщало "ALARM=1/0". Мы сохраняем его, т.к. оно уже
     * используется в логах/мониторе. В Этапе 4.5 мы вводим доп. события SIGNAL_ON/OFF,
     * чтобы отделить "нажатие кнопки" от "фактического режима сигнализации".
     */
    EVT_DOOR_ALARM,

    /* ------------------------------------------------------------
     * ЭТАП 4.3/4.4: тайм-ауты
     * ------------------------------------------------------------ */

    /* Тайм-аут допустимого открытого состояния (общий, из конфигурации).
     * При превышении:
     *  - включается режим сигнализации;
     *  - логика блокировки других дверей продолжает действовать.
     */
    EVT_DOOR_OPEN_TIMEOUT,

    /* Тайм-аут после закрытия двери (индивидуально на дверь, из конфигурации).
     * Это НЕ "логика зависимостей" — это сигнал Logic Core:
     * "по этой двери можно применять зависимую логику (если нужна)".
     */
    EVT_DOOR_POST_CLOSE_READY,

    /* ------------------------------------------------------------
     * ЭТАП 4.5: сигнализация как система (с причинами)
     * ------------------------------------------------------------ */

    /* Включение сигнализации.
     * arg = bitmask причин (door_alarm_reason_t), чтобы верхние уровни (лог/WEB/CAN)
     * понимали "почему" включилась сигнализация.
     */
    EVT_DOOR_SIGNAL_ON,

    /* Выключение сигнализации.
     * arg = 0 (или можно использовать текущую маску, но обычно достаточно 0).
     */
    EVT_DOOR_SIGNAL_OFF,

    /* ------------------------------------------------------------
     * System -> Door (команды)
     * ------------------------------------------------------------ */
    EVT_CMD_LOCK,
    EVT_CMD_UNLOCK,

    /* ------------------------------------------------------------
     * Network / system
     * ------------------------------------------------------------ */
    EVT_NET_LINK_UP,
    EVT_NET_LINK_DOWN,

    EVT_SYSTEM_FAULT

} app_event_type_t;

/* Источник события/команды (для приоритетов и трассировки) */
typedef enum
{
    APP_SRC_NONE = 0,

    /* Локальные/внутренние источники */
    APP_SRC_DOOR_LOCAL,
    APP_SRC_SUPERVISOR,
    APP_SRC_WATCHDOG,

    /* Внешние интерфейсы */
    APP_SRC_CAN,
    APP_SRC_RS485,
    APP_SRC_HTTP

} app_event_source_t;

typedef struct
{
    app_event_type_t   type;
    app_event_source_t source;

    uint8_t            door_id;     /* 1..N, 0 if N/A */
    uint8_t            _rsvd8;
    uint16_t           flags;

    uint32_t           arg;
    uint32_t           ttl_ms;
    uint32_t           timestamp;

} app_event_t;

void AppEvents_Init(void);
BaseType_t AppEvents_Publish(const app_event_t *evt, TickType_t ticks_to_wait);
BaseType_t AppEvents_Wait(app_event_t *evt, TickType_t ticks_to_wait);
